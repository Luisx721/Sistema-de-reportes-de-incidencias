
CREATE TABLE rol (
    id_rol        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    r_nombre      VARCHAR(50)  NOT NULL UNIQUE,
    r_descripcion VARCHAR(200),
    r_activo      BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE areas (
    id_area          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    a_nombre         VARCHAR(100) NOT NULL UNIQUE,
    a_tipo           VARCHAR(50),
    a_es_responsable BOOLEAN      NOT NULL DEFAULT FALSE,
    a_activo         BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE usuarios (
    id_usuario         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol             INT          NOT NULL REFERENCES rol(id_rol),
    id_area            INT          REFERENCES areas(id_area),
    u_nombre           VARCHAR(100) NOT NULL,
    u_correo           VARCHAR(150) NOT NULL UNIQUE,
    u_password         VARCHAR(255) NOT NULL,
    u_vinculo          VARCHAR(100) NOT NULL,
    u_correo_verificado BOOLEAN     NOT NULL DEFAULT FALSE,
    u_activo           BOOLEAN      NOT NULL DEFAULT TRUE,
    u_fecha_registro   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE categorias (
    id_categoria  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_area       INT          NOT NULL REFERENCES areas(id_area),
    c_nombre      VARCHAR(100) NOT NULL UNIQUE,
    c_descripcion VARCHAR(200),
    c_activo      BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE edificios (
    id_edificio INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    e_nombre    VARCHAR(200) NOT NULL UNIQUE,
    e_activo    BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE ubicaciones (
    id_ubicacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_edificio  INT          NOT NULL REFERENCES edificios(id_edificio),
    ub_nombre    VARCHAR(100) NOT NULL,
    ub_tipo      VARCHAR(50),
    ub_activo    BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE incidencias (
    id_incidencia         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario            INT          REFERENCES usuarios(id_usuario),
    id_categoria          INT          NOT NULL REFERENCES categorias(id_categoria),
    id_ubicacion          INT          NOT NULL REFERENCES ubicaciones(id_ubicacion),
    id_area_solicitante   INT          REFERENCES areas(id_area),
    i_codigo_seguimiento  VARCHAR(15)  NOT NULL UNIQUE
                          CHECK (LENGTH(i_codigo_seguimiento) >= 8),
    i_reportante_nombre   VARCHAR(100),
    i_reportante_vinculo  VARCHAR(50)
                          CHECK (i_reportante_vinculo IN
                            ('Estudiante','Docente','Personal Administrativo','Ordenanza','Jefatura')),
    i_descripcion         TEXT         NOT NULL CHECK (LENGTH(i_descripcion) >= 20),
    i_urgencia            VARCHAR(10)  CHECK (i_urgencia IN ('Baja','Media','Alta')),
    i_prioridad           VARCHAR(10)  CHECK (i_prioridad IN ('Baja','Media','Alta')),
    i_estado_actual       VARCHAR(50)  NOT NULL DEFAULT 'Recibido'
                          CHECK (i_estado_actual IN
                            ('Recibido','En proceso','En espera de materiales/autorización',
                             'Resuelto','Rechazado/Cerrado')),
    i_fecha_creacion      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    i_fecha_actualizacion TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    i_modalidad_origen    VARCHAR(20)  NOT NULL
                          CHECK (i_modalidad_origen IN ('Comunitario','Asistido')),
    i_fecha_cierre        TIMESTAMP
);

CREATE TABLE historial_estados (
    id_historial          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_incidencia         INT         NOT NULL REFERENCES incidencias(id_incidencia),
    id_usuario_encargado  INT         REFERENCES usuarios(id_usuario),
    he_estado             VARCHAR(50) NOT NULL
                          CHECK (he_estado IN
                            ('Recibido','En proceso','En espera de materiales/autorización',
                             'Resuelto','Rechazado/Cerrado')),
    he_observacion        TEXT        NOT NULL CHECK (LENGTH(he_observacion) >= 10),
    he_fecha_hora         TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Solo el registro inicial 'Recibido' puede no tener usuario
    CONSTRAINT ck_historial_usuario
        CHECK (id_usuario_encargado IS NOT NULL OR he_estado = 'Recibido')
);

CREATE TABLE fotografias (
    id_foto          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_incidencia    INT          NOT NULL REFERENCES incidencias(id_incidencia),
    f_orden          INT          NOT NULL CHECK (f_orden BETWEEN 1 AND 3),
    f_archivo        VARCHAR(250) NOT NULL,
    f_tipo           VARCHAR(20)  NOT NULL CHECK (f_tipo IN ('jpg','jpeg','png')),
    f_tamano_bytes   INT          NOT NULL CHECK (f_tamano_bytes > 0 AND f_tamano_bytes <= 5242880),
    CONSTRAINT uq_foto_incidencia_orden UNIQUE (id_incidencia, f_orden)
);

CREATE TABLE auditoria (
    id_auditoria      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario        INT         REFERENCES usuarios(id_usuario),
    au_origen         VARCHAR(20) NOT NULL CHECK (au_origen IN ('USUARIO','SISTEMA')),
    au_tabla          VARCHAR(50) NOT NULL,
    au_id_registro    INT         NOT NULL,
    au_accion         VARCHAR(20) NOT NULL CHECK (au_accion IN ('INSERT','UPDATE','DELETE')),
    au_valor_anterior TEXT,
    au_valor_nuevo    TEXT,
    au_fecha_hora     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Índices para los filtros del panel (RF-15)
CREATE INDEX idx_incidencias_categoria ON incidencias(id_categoria);
CREATE INDEX idx_incidencias_ubicacion ON incidencias(id_ubicacion);
CREATE INDEX idx_incidencias_estado    ON incidencias(i_estado_actual);
CREATE INDEX idx_historial_incidencia  ON historial_estados(id_incidencia);